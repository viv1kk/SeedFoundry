def test_the_same_approval_twice_gives_the_same_files_zip_page_and_events(tmp_path):
    runs = []
    for name in ("one", "two"):
        clock = FakeClock(auto=False)
        with TestClient(create_app(tmp_path / name, clock)) as client:
            two_iterations(client, clock)
            page = approve(client, "b-2").json()
            page["approval"].pop("approved_at")
            events = [{k: v for k, v in e.model_dump(mode="json").items() if k != "wall_ts"} for e in client.app.state.lab.log.after(0)]
            runs.append((downloads(client), page, events))
    assert runs[0] == runs[1]


