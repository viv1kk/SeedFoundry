def test_approved_iteration_2_files_are_the_layers_the_build_planted_byte_for_byte(paths):
    for iteration in PATHS:
        build = sample_builds()[iteration - 1]
        uploads = {e.data["path"].rsplit("/", 1)[-1]: e.data for e in build.log if e.type == "api.call" and e.step == "contain.upload"}
        manifest = next(e.data["manifest"] for e in build.log if e.step == "synth.manifest" and e.type == "log")
        for name, text in paths[iteration].items():
            planted = text.split("\n## Known issues\n")[0].rstrip("\n") + "\n" if iteration == 1 else text
            layer = next(item for item in manifest["layers"] if item["name"] == name)
            assert (layer["sha256"], layer["bytes"]) == (package.digest(planted), len(planted.encode("utf-8")))
            assert uploads[name]["response"]["sha256"] == package.digest(planted)


