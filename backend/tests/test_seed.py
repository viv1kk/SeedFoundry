def test_a_missing_section_says_so_and_headings_move_under_the_layer():
    music = "# Seed X\n\nA lead.\n\n## Purpose\n\nDo the thing.\n\n```\n## not a heading\n```\n"
    environment = (
        "# Env\n\n## Protection Layer\n\nTop rule.\n\n### Access control\n\n- Only staff.\n\n#### Detail\n\nDeep.\n\n"
        "### Reconciliation\n\n- Sums agree.\n\n### Something else\n\n- Kept.\n"
    )
    made = layers.drafts(intake(music=music, environment=environment), "Seed X", 1, "abc123")
    core, protection = made["core.md"], made["protection.md"]
    assert h2(core) == SECTIONS["core.md"]
    assert section(core, "Core principles").strip() == layers.NOTHING
    assert "```\n## not a heading\n```" in core
    assert section(core, "Purpose").strip().startswith("A lead.")
    # Each Protection Layer sub-section goes under the section its title names, guardrails otherwise.
    assert "- Only staff." in section(protection, "Security") and "### Detail" in section(protection, "Security")
    assert "- Sums agree." in section(protection, "Validation checks")
    assert "Top rule." in section(protection, "Guardrails") and "- Kept." in section(protection, "Guardrails")
    assert section(protection, "Quality controls").strip() == layers.NOTHING
    assert "Nothing is stated" in section(made["adaptation.md"], "Data sources and mappings")


