def finish(client: TestClient, clock: FakeClock) -> None:
    assert client.post("/api/demo/skip", json={"to": "build"}).status_code == 200
    client.portal.call(clock.advance, SLICE)
    client.portal.call(client.app.state.engine.wait)


def first_iteration(client: TestClient, clock: FakeClock) -> None:
    assert client.post("/api/demo/sample", json={}).status_code == 201
    assert client.post("/api/builds", json={}).status_code == 201
    finish(client, clock)


def two_iterations(client: TestClient, clock: FakeClock) -> None:
    first_iteration(client, clock)
    assert client.post("/api/builds", json={"iteration": 2, "feedback": demo_feedback()}).status_code == 201
    finish(client, clock)


def approve(client: TestClient, build_id: str):
    return client.post("/api/seed/approve", json={"build_id": build_id})


def downloads(client: TestClient) -> tuple[dict[str, bytes], bytes]:
    return {name: client.get(f"/api/seed/files/{name}").content for name in layers.NAMES}, client.get("/api/seed/zip").content


def test_approving_iteration_2_records_it_and_serves_the_seed(api, clock, paths):
    two_iterations(api, clock)
    seq = api.app.state.lab.state.seq
    response = approve(api, "b-2")
    assert response.status_code == 201
    page = response.json()
    assert api.get("/api/seed").json() == page
    assert {k: page["approval"][k] for k in ("iteration", "build_id")} == {"iteration": 2, "build_id": "b-2"}
    assert page["approval"]["approved_at"]
    assert api.get("/api/state").json()["approval"]["build_id"] == "b-2"
    assert page["known_issues"] == []
    assert [f["name"] for f in page["files"]] == list(layers.NAMES)
    assert {f["name"]: f["content"] for f in page["files"]} == paths[2]
    # One event, outside any build, so no build's console shows it.
    [event] = api.app.state.lab.log.after(seq)
    assert (event.type, event.build_id, event.data["known_issues"]) == ("seed.approved", None, [])
    assert event.message == 'Seed approved: "License Optimization", iteration 2; 3 files, no known issues'


def test_each_file_and_the_zip_download_and_the_zip_holds_exactly_the_three_files(api, clock, paths):
    two_iterations(api, clock)
    approve(api, "b-2")
    for name in layers.NAMES:
        response = api.get(f"/api/seed/files/{name}")
        assert response.status_code == 200
        assert response.headers["content-type"] == "text/markdown; charset=utf-8"
        assert response.headers["content-disposition"] == f'attachment; filename="{name}"'
        assert response.content == paths[2][name].encode("utf-8")
    response = api.get("/api/seed/zip")
    assert response.headers["content-type"] == "application/zip"
    assert response.headers["content-disposition"] == 'attachment; filename="license-optimization-seed.zip"'
    archive = zipfile.ZipFile(io.BytesIO(response.content))
    assert archive.namelist() == list(layers.NAMES)
    files, _ = downloads(api)
    for info in archive.infolist():
        assert archive.read(info) == files[info.filename]
        assert info.date_time == package.ZIP_TIME
    assert api.get("/api/seed").json()["zip"]["bytes"] == len(response.content)
    assert api.get("/api/seed/zip").content == response.content


