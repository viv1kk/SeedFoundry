def intake(**overrides: str) -> list[IntakeFile]:
    files = [IntakeFile(id=f"f-{i}", name=name, category=category, content=content) for i, (name, category, content) in enumerate(sample_files())]
    for name, content in overrides.items():
        files = [f.model_copy(update={"content": content}) if f.category.value == name else f for f in files]  # by category (D-85)
