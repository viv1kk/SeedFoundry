def test_refusals(api, clock):
    assert api.get("/api/seed").json()["detail"]["code"] == "seed_not_approved"
    assert api.get("/api/seed/files/core.md").status_code == 404
    assert api.get("/api/seed/zip").status_code == 404
    assert approve(api, "b-9").json()["detail"]["code"] == "build_not_found"
    assert api.post("/api/demo/sample", json={}).status_code == 201
    assert api.post("/api/builds", json={}).status_code == 201
    running = approve(api, "b-1")
    assert (running.status_code, running.json()["detail"]["code"]) == (409, "build_running")
    finish(api, clock)
    assert api.post("/api/builds", json={"iteration": 2, "feedback": demo_feedback()}).status_code == 201
    finish(api, clock)
    # Iteration 1 cannot be approved once iteration 2 has started (D-73).
    superseded = approve(api, "b-1")
    assert (superseded.status_code, superseded.json()["detail"]["code"]) == (409, "iteration_superseded")
    assert api.app.state.lab.state.approval is None
    assert approve(api, "b-2").status_code == 201
    again = approve(api, "b-2")
    assert (again.status_code, again.json()["detail"]["code"]) == (409, "seed_approved")
    # A build after approval is refused (D-49).
    build = api.post("/api/builds", json={})
    assert (build.status_code, build.json()["detail"]["code"]) == (409, "seed_approved")
    assert api.get("/api/seed/files/manifest.json").json()["detail"]["code"] == "seed_file_not_found"


